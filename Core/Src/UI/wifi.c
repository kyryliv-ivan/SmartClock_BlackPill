void wifi_qr_draw(void)
{
	oled_clear();
	/* centered: (128-64)/2 = 32, (64-64)/2 = 0 - fills the full screen
	   height */
	oled_draw_bitmap(32, 0, wifi_qr_bitmap, WIFI_QR_W, WIFI_QR_H);
	oled_flush();
}

