#include "wifi.h"
#include "oled.h"
#include <string.h>

static const char *labels[] = { "Status", "Reconnect", "Forget WiFi" };
#define COUNT (sizeof(labels) / sizeof(labels[0]))

static uint8_t connected = 0;
static char    ssid[32] = "";

uint8_t wifi_submenu_count(void) { return COUNT; }

const char *wifi_submenu_label(uint8_t index)
{
	return labels[index];
}

wifi_action_t wifi_submenu_tap(uint8_t index)
{
	if (index == 2) /* Forget WiFi */
		return WIFI_ACTION_FORGET;

	return WIFI_ACTION_NONE; /* Status / Reconnect handled by menu.c */
}

void wifi_connected_set(uint8_t c) { connected = c; }
uint8_t wifi_connected_get(void)   { return connected; }

void wifi_ssid_set(const char *s)
{
	strncpy(ssid, s, sizeof(ssid) - 1);
	ssid[sizeof(ssid) - 1] = '\0';
}

const char *wifi_ssid_get(void) { return ssid; }

/* QR payload: "WIFI:T:WPA;S:SmartClock;P:SmartClock;;" - fixed setup AP
   credentials (SSID and password both "SmartClock", 10 chars - clears
   WPA2's 8-character minimum), so the QR pattern itself is always the
   same and can be pre-rendered once instead of encoded on-device.
   31x31 modules at 2x2px each = 62x62px is the largest *clean* integer
   scale that fits the 64px-tall screen (3px/module would need 93px) -
   nearest-neighbor stretched by 2px to 64x64 (fills the screen height
   exactly) and re-verified against a live decoder afterwards, so a
   couple of module edges are 3px instead of 2px rather than leaving
   margin unused. Quiet zone trimmed to 1 module before the stretch (0
   fails to scan, 1 decodes reliably - verified separately). Row-major
   MSB-first (matches ssd1306_DrawBitmap / oled_draw_bitmap format) -
   verified bit-for-bit against the source QR matrix before embedding. */
